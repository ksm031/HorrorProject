// draw one 14×14 syllable; bold doubles strokes rightward; spray adds specks + drips
function glyph(b, ch, x, y, c, o = {}) {
  const g = GLYPH[ch]; if (!g) return;
  const r = rng(o.seed || (x * 31 + y)); let drips = 0;
  for (let j = 0; j < 14; j++) for (let i = 0; i < 14; i++) {
    if (g[j][i] !== '#') continue;
    P(b, x + i, y + j, c); if (o.bold) P(b, x + i + 1, y + j, c);
    if (o.spray) {
      if (r() < 0.025) P(b, x + i + ri((r() - 0.5) * 7), y + j + ri((r() - 0.5) * 7), c);
      const below = j < 13 && g[j + 1][i] === '#', above = j > 0 && g[j - 1][i] === '#';
      const end = !below && (above || (i < 13 && g[j][i + 1] !== '#') || (i > 0 && g[j][i - 1] !== '#'));
      if (end && drips < 3 && r() < 0.3 * o.spray) {
        drips++; const l = 2 + ri(r() * 7 * o.spray);
        for (let k = 1; k <= l; k++) P(b, x + i, y + j + k, k >= l - 1 ? DN[c] : c);
        P(b, x + i, y + j + l + 1, DN[c]);
      }
    }
  }
}
function hangul(b, str, x, y, c, o = {}) {
  let cx = x; const adv = 14 + (o.bold ? 2 : 1) + (o.gap || 0);
  for (const ch of str) { if (ch === ' ') { cx += 7; continue; } glyph(b, ch, cx, y, c, o); cx += adv; }
  return cx - x;
}
// tiny 3×5 digits for apartment block numbers
const DIG = ['111101101101111', '010110010010111', '111001111100111', '111001111001111', '101101111001001',
  '111100111001111', '111100111101111', '111001001001001', '111101111101111', '111101111001111'];
function digits(b, str, x, y, c) {
  let cx = x;
  for (const ch of str) { const g = DIG[+ch]; for (let i = 0; i < 15; i++) if (g[i] === '1') P(b, cx + i % 3, y + (i / 3 | 0), c); cx += 4; }
}
