const { chromium } = require('playwright'); const path = require('path');
(async () => {
  const out = process.argv[2];
  const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
  const errs = [];
  const p = await b.newPage({ viewport: { width: 1280, height: 760 } });
  p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await p.goto('file://' + path.resolve(__dirname, '../index.html'));
  await p.waitForFunction('window.__ready === true');
  await p.screenshot({ path: out + '_veil.png' });
  const time = () => p.$eval('#time', e => e.textContent);
  await p.click('#go'); await p.waitForTimeout(2500);
  console.log('after 2.5s:', await time(), 'ctx', await p.evaluate(() => AU.ctx && AU.ctx.state));
  await p.keyboard.press('Space'); const a = await time(); await p.waitForTimeout(800); const bb = await time();
  console.log('paused', a, '->', bb, a === bb ? 'OK (held)' : 'MOVED');
  await p.keyboard.press('Space'); await p.keyboard.press('ArrowRight'); await p.keyboard.press('ArrowRight'); await p.waitForTimeout(300);
  console.log('after +10s seek:', await time());
  const box = await p.$eval('#rail', e => { const r = e.getBoundingClientRect(); return [r.left, r.top, r.width]; });
  await p.mouse.move(box[0] + box[2] * 0.985, box[1] + 2); await p.mouse.down(); await p.mouse.up();
  await p.waitForTimeout(2200);
  console.log('end veil visible:', await p.$eval('#veil', e => !e.hidden), 'button:', await p.$eval('#go', e => e.textContent));
  await p.screenshot({ path: out + '_end.png' });
  await p.click('#go'); await p.waitForTimeout(1000); console.log('replay ->', await time());
  console.log('errors:', errs.length ? errs : 'none');
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3 });
  await m.goto('file://' + path.resolve(__dirname, '../index.html')); await m.waitForFunction('window.__ready === true');
  console.log('mobile canvas css size', await m.$eval('#c', e => e.style.width + ' x ' + e.style.height), 'scrollW', await m.evaluate(() => document.documentElement.scrollWidth));
  await m.screenshot({ path: out + '_mobile.png' });
  await b.close();
})();
